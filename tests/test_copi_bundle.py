def test_hook_renders_the_engines_real_credential_rows(tmp_path: Path, monkeypatch) -> None:
    """The row keys the hook reads are the ones `memoria doctor --json` actually emits.

    The stub-PATH goldens above prove the rendering against a hand-written
    report; this proves the report shape itself by producing it from the engine,
    so a renamed row key fails here instead of silently emptying the hook.
    """
    from memoria_vault.product.copi_skill import session_status
    from memoria_vault.runtime.secrets import CREDENTIAL_REGISTRY, credential_report

    copy_memoria_dirs(tmp_path, "config")
    for entry in CREDENTIAL_REGISTRY:
        monkeypatch.delenv(str(entry["name"]), raising=False)
    monkeypatch.delenv("KILOCODE_API_KEY", raising=False)

    rows = credential_report(tmp_path, loaded_from_file=())
    lines = session_status._credential_lines(rows)

    assert all(row["status"] == "unset" for row in rows)
    assert len(lines) == len([row for row in rows if row["class"] != "identity"])
    assert (
        "Memoria: credential KILOCODE_API_KEY is unset (required-for-operation) — "
        "live-model calls refuse before the network; "
        "run `memoria secrets set KILOCODE_API_KEY`."
    ) in lines
    assert (
        "Memoria: credential OPENALEX_API_KEY is unset (enhancing) — "
        "openalex keyless polite-pool mode (lower rate limits)."
    ) in lines
    assert not [line for line in lines if "NCBI_EMAIL" in line]
    assert session_status.DEFAULT_ENHANCING_EFFECT not in "\n".join(lines)
