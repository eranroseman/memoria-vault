def _stub_memoria(bin_dir: Path, stdout_payload: str) -> None:
    """Put a `memoria` on PATH that prints one canned doctor report.

    The stub is a Python script, not a shell script: the hook's PATH holds only
    this directory, so a `/bin/sh` stub reaching for `cat` would fail to resolve
    it and every stubbed case would collapse into the doctor-unavailable branch.

    It answers only the exact argv the hook is supposed to send. A stub that
    printed its payload for any argv would let the hook drop `--json` (and get
    back human-readable text on a real machine) with every test still green.
    """
    bin_dir.mkdir(parents=True, exist_ok=True)
    stub = bin_dir / "memoria"
    stub.write_text(
        f"#!{sys.executable}\n"
        "import sys\n"
        'if sys.argv[1:] == ["doctor", "--json"]:\n'
        f"    sys.stdout.write({stdout_payload!r})\n",
        encoding="utf-8",
    )
    stub.chmod(0o755)


def _run_seeded_hook(tmp_path: Path, path_dir: Path) -> str:
    hook = tmp_path / ".claude/hooks/session_status.py"
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(render_session_status_hook(), encoding="utf-8")
    proc = subprocess.run(
        [sys.executable, str(hook)],
        capture_output=True,
        cwd=tmp_path,
        env={"PATH": str(path_dir)},
        timeout=60,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr.decode("utf-8", "replace")
    return proc.stdout.decode("utf-8")


